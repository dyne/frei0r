import { createHash } from 'node:crypto'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const demoDirectory = join(process.cwd(), '.vitepress', 'dist', 'demo')

if (!existsSync(join(demoDirectory, 'index.html'))) {
  throw new Error('Build the demo before writing its service worker.')
}

function filesIn(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name)
    return entry.isDirectory() ? filesIn(path) : [path]
  })
}

const precache = filesIn(demoDirectory)
  .map((path) => `./${relative(demoDirectory, path).replaceAll('\\', '/')}`)
  .filter((path) =>
    path === './index.html' ||
    path === './manifest.webmanifest' ||
    /^\.\/assets\/.+\.(?:css|js)$/.test(path) ||
    /^\.\/icons\/.+\.png$/.test(path) ||
    /^\.\/runtime\/.+\.(?:json|mjs|wasm)$/.test(path),
  )
  .sort()

if (!precache.includes('./index.html') ||
  !precache.some((path) => path.endsWith('.mjs')) ||
  !precache.some((path) => path.endsWith('.wasm'))) {
  throw new Error('The demo build is missing an app shell or browser runtime product.')
}

const revisionHash = createHash('sha256')
for (const path of precache) {
  revisionHash.update(readFileSync(join(demoDirectory, path.slice(2))))
}
const revision = revisionHash.digest('hex').slice(0, 16)

const source = `/* Generated by scripts/write-demo-service-worker.mjs. */
const cacheName = 'frei0r-demo-shell-${revision}'
const precache = ${JSON.stringify(precache)}
const scopePath = new URL(self.registration.scope).pathname

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(cacheName).then((cache) => cache.addAll(precache)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(
    keys.filter((key) => key.startsWith('frei0r-demo-shell-') && key !== cacheName).map((key) => caches.delete(key)),
  )).then(() => self.clients.claim()))
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  const url = new URL(request.url)
  if (request.method !== 'GET' || url.origin !== self.location.origin || !url.pathname.startsWith(scopePath)) return

  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).then((response) => {
      const copy = response.clone()
      void caches.open(cacheName).then((cache) => cache.put('./index.html', copy))
      return response
    }).catch(() => caches.match('./index.html')))
    return
  }

  event.respondWith(caches.match(request).then((cached) => cached || fetch(request)))
})
`

writeFileSync(join(demoDirectory, 'service-worker.js'), source)
console.log(`Wrote service worker with ${precache.length} demo-only assets.`)
